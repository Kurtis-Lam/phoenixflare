piece_tables = {
    chess.PAWN: pawn,
    chess.KNIGHT: knight,
    chess.BISHOP: bishop,
    chess.ROOK: rook,
    chess.QUEEN: queen,
    chess.KING: king
}

def eval_positions(board):
    """
    Returns the total positional evaluation: 
    (white's position score) minus (black's position score).
    """
    evaluation = 0
    for square, piece in board.piece_map().items():
        table = piece_tables.get(piece.piece_type)
        if table:
            # For white pieces, use the table value directly;
            # for black pieces, mirror the square (since tables are made for white).
            index = square if piece.color == chess.WHITE else chess.square_mirror(square)
            if piece.color == chess.WHITE:
                evaluation += table[index]
            else:
                evaluation -= table[index]
    return evaluation